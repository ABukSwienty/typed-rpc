#!/usr/bin/env node
// Generate equivalent basic, trpc-like and tRPC (with and without zod) routers
// of N procedures each, plus a usage file that calls every procedure, so
// type-checking cost can be compared as the API grows.
//
// Output: bench/generated/n<N>/{basic,trpc-like,trpc,trpc-zod}/{server,client,usage}.ts
// (outside src/ so the normal project type check doesn't pick them up)
//
// Usage:
//   node scripts/gen-bench.mjs [options] [sizes...]
//
// Options:
//   --per-router <n>   procedures per nested router (default 10)
//   --bench            run bench-types on every generated usage.ts afterwards
//   --runs <n>         passed through to bench-types (default 3)
//
// Sizes default to 1 10 50 100 250.

import { spawnSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.cwd();
const outDir = join(root, "bench", "generated");

const parseArgs = (argv) => {
  const opts = { perRouter: 10, bench: false, runs: 3, sizes: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--per-router") opts.perRouter = Number(argv[++i]);
    else if (arg === "--bench") opts.bench = true;
    else if (arg === "--runs") opts.runs = Number(argv[++i]);
    else if (arg.startsWith("--")) throw new Error(`Unknown option: ${arg}`);
    else opts.sizes.push(Number(arg));
  }
  if (!opts.sizes.length) opts.sizes = [1, 10, 50, 100, 250];
  for (const n of [...opts.sizes, opts.perRouter, opts.runs]) {
    if (!Number.isInteger(n) || n < 1) throw new Error(`Expected a positive integer, got ${n}`);
  }
  return opts;
};

// Procedure i lives at router<r>.proc<i>. Inputs and outputs carry an
// index-specific field so every procedure has a distinct type, like a real API.
const procedures = (n, perRouter) =>
  Array.from({ length: n }, (_, i) => ({
    router: `router${Math.floor(i / perRouter)}`,
    name: `proc${i}`,
    input: `{ id: string; field${i}: number }`,
    schema: `z.object({ id: z.string(), field${i}: z.number() })`,
    output: `{ id: "id-${i}", value${i}: "foo" }`,
    callArgs: `{ id: "1", field${i}: ${i} }`,
    resultField: `value${i}`,
  }));

const groupByRouter = (procs) => {
  const groups = new Map();
  for (const proc of procs) groups.set(proc.router, [...(groups.get(proc.router) ?? []), proc]);
  return groups;
};

const header = (n) => `// Generated by scripts/gen-bench.mjs (${n} procedures). Do not edit.\n`;

const basicFiles = (n, procs) => {
  const routers = [...groupByRouter(procs)]
    .map(([router, list]) => {
      const body = list
        .map((p) => `    ${p.name}: async (params: ${p.input}) => (${p.output}),`)
        .join("\n");
      return `  ${router}: {\n${body}\n  },`;
    })
    .join("\n");

  const calls = procs
    .map((p, i) => `  const r${i} = await rpcClient("${p.router}.${p.name}", [${p.callArgs}]);\n  r${i}.${p.resultField};`)
    .join("\n");

  return {
    "server.ts": `${header(n)}export const protocols = {\n${routers}\n};\n`,
    // The generic helpers are imported from the example; only Protocols is local.
    "client.ts": `${header(n)}import type {
  ProtocolParams,
  ProtocolPaths,
  ProtocolResponse,
} from "@/examples/basic/types";
import type { protocols } from "./server";

type Protocols = typeof protocols;

export const rpcClient = async <Path extends ProtocolPaths<Protocols>>(
  path: Path,
  params: ProtocolParams<Protocols, Path>,
) => {
  const response = await fetch("api/rpc", {
    method: "POST",
    body: JSON.stringify({ path, params }),
  });

  const result = await response.json();

  return result as ProtocolResponse<Protocols, Path>;
};
`,
    "usage.ts": `${header(n)}import { rpcClient } from "./client";\n\nexport const run = async () => {\n${calls}\n};\n`,
  };
};

const trpcLikeFiles = (n, procs) => {
  const routers = [...groupByRouter(procs)]
    .map(([router, list]) => {
      const body = list
        .map(
          (p) =>
            `    ${p.name}: procedure\n      .input(${p.schema})\n      .handler(async (params) => (${p.output})),`,
        )
        .join("\n");
      return `  ${router}: {\n${body}\n  },`;
    })
    .join("\n");

  // trpc-like takes the handler's single argument directly, not a tuple.
  const calls = procs
    .map((p, i) => `  const r${i} = await rpcClient("${p.router}.${p.name}", ${p.callArgs});\n  r${i}.${p.resultField};`)
    .join("\n");

  return {
    "server.ts": `${header(n)}import { z } from "zod";
import { procedure } from "@/examples/trpc-like/rpc";

export const protocols = {
${routers}
};
`,
    "client.ts": `${header(n)}import type {
  ProtocolArgs,
  ProtocolPaths,
  ProtocolResponse,
} from "@/examples/trpc-like/types";
import type { protocols } from "./server";

type Protocols = typeof protocols;

export const rpcClient = async <Path extends ProtocolPaths<Protocols>>(
  path: Path,
  ...[params]: ProtocolArgs<Protocols, Path>
) => {
  const response = await fetch("api/rpc", {
    method: "POST",
    body: JSON.stringify({ path, params }),
  });

  const result = await response.json();

  return result as ProtocolResponse<Protocols, Path>;
};
`,
    "usage.ts": `${header(n)}import { rpcClient } from "./client";\n\nexport const run = async () => {\n${calls}\n};\n`,
  };
};

// With zod, inputs are validated by a schema like trpc-like; without it, a
// type-asserting parser keeps validation-library cost out of the comparison.
const trpcFiles = (n, procs, { zod = false } = {}) => {
  const routers = [...groupByRouter(procs)]
    .map(([router, list]) => {
      const body = list
        .map(
          (p) =>
            `    ${p.name}: t.procedure\n      .input(${zod ? p.schema : `(input) => input as ${p.input}`})\n      .query(async ({ input }) => (${p.output})),`,
        )
        .join("\n");
      return `  ${router}: t.router({\n${body}\n  }),`;
    })
    .join("\n");

  const calls = procs
    .map((p, i) => `  const r${i} = await rpcClient.${p.router}.${p.name}.query(${p.callArgs});\n  r${i}.${p.resultField};`)
    .join("\n");

  return {
    "server.ts": `${header(n)}import { initTRPC } from "@trpc/server";${zod ? `\nimport { z } from "zod";` : ""}

const t = initTRPC.create();

export const appRouter = t.router({
${routers}
});

export type AppRouter = typeof appRouter;
`,
    "client.ts": `${header(n)}import { createTRPCClient, httpLink } from "@trpc/client";
import type { AppRouter } from "./server";

export const rpcClient = createTRPCClient<AppRouter>({
  links: [httpLink({ url: "api/rpc" })],
});
`,
    "usage.ts": `${header(n)}import { rpcClient } from "./client";\n\nexport const run = async () => {\n${calls}\n};\n`,
  };
};

const writeVariant = (dir, files) => {
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of Object.entries(files)) writeFileSync(join(dir, name), content);
};

const main = () => {
  const opts = parseArgs(process.argv.slice(2));
  rmSync(outDir, { recursive: true, force: true });

  const usageFiles = [];
  for (const n of opts.sizes) {
    const procs = procedures(n, opts.perRouter);
    const sizeDir = join(outDir, `n${n}`);
    const variants = {
      basic: basicFiles(n, procs),
      "trpc-like": trpcLikeFiles(n, procs),
      trpc: trpcFiles(n, procs),
      "trpc-zod": trpcFiles(n, procs, { zod: true }),
    };
    for (const [variant, files] of Object.entries(variants)) {
      writeVariant(join(sizeDir, variant), files);
      usageFiles.push(join(sizeDir, variant, "usage.ts"));
    }
  }
  console.log(`Generated ${opts.sizes.length} size(s) in ${relative(root, outDir)}/: ${opts.sizes.join(", ")}`);

  if (opts.bench) {
    const files = usageFiles.map((f) => relative(root, f));
    const result = spawnSync("node", ["scripts/bench-types.mjs", "--runs", String(opts.runs), ...files], {
      stdio: "inherit",
    });
    process.exit(result.status ?? 1);
  }
};

main();
